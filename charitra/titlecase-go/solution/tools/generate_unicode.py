#!/usr/bin/env python3
"""Freeze CPython 3.12 Unicode semantics as Go source, never task answers.

This authoring-only generator is not copied into the candidate repository.
Run from anywhere: python3 -S solution/tools/generate_unicode.py
"""
from pathlib import Path
import sys
import unicodedata

if sys.version_info[:2] != (3, 12):
    raise SystemExit('Generate these tables using Python 3.12, the reference runtime.')
if unicodedata.unidata_version != '15.0.0':
    raise SystemExit(f'Expected Unicode 15.0.0, got {unicodedata.unidata_version}')


def quote_go(text):
    result = ['"']
    for ch in text:
        n = ord(ch)
        if ch in ('"', '\\'):
            result.append('\\' + ch)
        elif 0x20 <= n <= 0x7E:
            result.append(ch)
        elif n <= 0xFFFF:
            result.append(f'\\u{n:04x}')
        else:
            result.append(f'\\U{n:08x}')
    return ''.join(result) + '"'


def ranges(values):
    if not values:
        return []
    result = []
    lo = hi = values[0]
    for n in values[1:]:
        if n == hi + 1:
            hi = n
        else:
            result.append((lo, hi))
            lo = hi = n
    result.append((lo, hi))
    return result


maps = {kind: {} for kind in ('upper', 'lower', 'title')}
properties = {kind: [] for kind in ('word', 'space', 'cased', 'caseIgnorable')}
for n in range(0x110000):
    if 0xD800 <= n <= 0xDFFF:
        continue  # UTF-8 input cannot contain surrogate code points.
    ch = chr(n)
    for kind in maps:
        converted = getattr(ch, kind)()
        if converted != ch:
            maps[kind][n] = converted
    if ch == '_' or ch.isalnum():
        properties['word'].append(n)
    if ch.isspace():
        properties['space'].append(n)
    if ch.islower() or ch.isupper() or ch.istitle():
        properties['cased'].append(n)
    # Derive the Unicode Case_Ignorable property from CPython's contextual
    # final-sigma behavior. The two probes distinguish ignorable cased
    # letters (e.g. modifiers) from non-ignorable cased letters as well.
    if ('A\u03a3' + ch + 'A').lower()[1] == '\u03c3' and (' ' + ch + '\u03a3').lower()[-1] == '\u03c3':
        properties['caseIgnorable'].append(n)

out = [
    '// Code generated by tools/generate_unicode.py; DO NOT EDIT.',
    '// Source: CPython 3.12 / Unicode 15.0.0 character properties and case mappings.',
    '// These are character tables, not title inputs or expected outputs.',
    'package main', '',
]
for kind, entries in maps.items():
    out.append(f'var py{kind.title()}Map = map[rune]string{{')
    out.extend(f'\t0x{n:X}: {quote_go(value)},' for n, value in entries.items())
    out.extend(['}', ''])
for kind, entries in properties.items():
    out.append(f'var py{kind[0].upper() + kind[1:]}Ranges = []runeRange{{')
    out.extend(f'\t{{0x{lo:X}, 0x{hi:X}}},' for lo, hi in ranges(entries))
    out.extend(['}', ''])
path = Path(__file__).resolve().parent.parent / 'unicode_tables.go'
path.write_text('\n'.join(out), encoding='utf-8')
print(f'Wrote {path.name}; Unicode {unicodedata.unidata_version}; {path.stat().st_size} bytes')
