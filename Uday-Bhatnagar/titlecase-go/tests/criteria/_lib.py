"""Shared helpers for the titlecase-go verifier criteria.

These helpers only run Go tooling and compare bytes.  They never reimplement
titlecase: expected answers come from the hidden dataset files that were
generated by the original Python implementation.
"""

from __future__ import annotations

import os
import subprocess
from pathlib import Path

BUILD_TIMEOUT_SEC = 120
RUN_TIMEOUT_SEC = 120
MAX_DETAIL_CHARS = 2000


def go_env() -> dict[str, str]:
    """A deterministic, offline Go environment."""
    env = os.environ.copy()
    env["GOPROXY"] = "off"
    env["GOTOOLCHAIN"] = "local"
    env["GOCACHE"] = env.get("GOCACHE") or "/tmp/go-build-cache"
    env["GOFLAGS"] = ""
    return env


def go_build(workspace: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["go", "build", "./..."],
        cwd=str(workspace),
        env=go_env(),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=BUILD_TIMEOUT_SEC,
    )


def go_build_binary(workspace: Path, output: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["go", "build", "-o", str(output), "."],
        cwd=str(workspace),
        env=go_env(),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=BUILD_TIMEOUT_SEC,
    )


def tail(text: str | None, limit: int = MAX_DETAIL_CHARS) -> str:
    text = (text or "").strip()
    if len(text) <= limit:
        return text
    return "..." + text[-limit:]


def describe_build(proc: subprocess.CompletedProcess[str]) -> str:
    if proc.returncode == 0:
        return "go build ./... succeeded"
    detail = tail(proc.stderr or proc.stdout)
    suffix = f": {detail}" if detail else ""
    return f"go build ./... failed (exit {proc.returncode}){suffix}"


def compare_lines(expected: bytes, actual: bytes) -> tuple[int, int, int | None, list[bytes], list[bytes]]:
    """Compare newline-delimited output, preserving every byte.

    A final newline is a terminator, not an extra record.  Extra output lines
    increase the denominator so that line-structure violations cannot score a
    perfect result.
    """
    expected_lines = expected.split(b"\n")
    if expected_lines and expected_lines[-1] == b"":
        expected_lines.pop()
    actual_lines = actual.split(b"\n")
    if actual_lines and actual_lines[-1] == b"":
        actual_lines.pop()

    total = max(len(expected_lines), len(actual_lines))
    correct = 0
    first_bad: int | None = None
    for index in range(min(len(expected_lines), len(actual_lines))):
        if expected_lines[index] == actual_lines[index]:
            correct += 1
        elif first_bad is None:
            first_bad = index
    if first_bad is None and len(actual_lines) != len(expected_lines):
        first_bad = min(len(expected_lines), len(actual_lines))
    return correct, total, first_bad, expected_lines, actual_lines


def describe_line(index: int, expected_lines: list[bytes], actual_lines: list[bytes]) -> str:
    expected_value = (
        expected_lines[index] if index < len(expected_lines) else b"<missing line>"
    )
    actual_value = actual_lines[index] if index < len(actual_lines) else b"<missing line>"
    return (
        f"first mismatch at line {index + 1}: "
        f"expected={expected_value[:200]!r} actual={actual_value[:200]!r}"
    )
