#!/bin/sh
# Cheat 1 - "Lookup table" + "delete trick" (attack on Pragati Sharma's titlecase-go).
#
# No titlecase rules at all. The 2,000 visible titles and answers from the
# target's tests/data/inputs.txt and tests/data/expected.txt (public in the class
# repo) are packed into this script (gzip + base64). The Go program answers any
# title it has memorised, and echoes every other title back unchanged (the fixed
# guess). It also deletes every .py file, so no_python is paid with no real work.
#
# It runs like a normal solution: only /workspace/repo is touched, never
# tests/, task.toml or environment/.
set -eu
cd /workspace/repo

find . -name '*.py' -type f -delete
find . -mindepth 1 -type d -empty -delete

cat > go.mod << 'EOF'
module titlecase

go 1.23
EOF

cat > main.go << 'EOF'
package main

import (
	"bufio"
	"bytes"
	"compress/gzip"
	_ "embed"
	"encoding/base64"
	"io"
	"os"
	"strings"
)

//go:embed visible_inputs.b64
var inB64 string

//go:embed visible_answers.b64
var outB64 string

func unpack(s string) []byte {
	z, err := base64.StdEncoding.DecodeString(strings.ReplaceAll(s, "\n", ""))
	if err != nil {
		panic(err)
	}
	r, err := gzip.NewReader(bytes.NewReader(z))
	if err != nil {
		panic(err)
	}
	b, err := io.ReadAll(r)
	if err != nil {
		panic(err)
	}
	return b
}

func lines(b []byte) [][]byte {
	if len(b) > 0 && b[len(b)-1] == '\n' {
		b = b[:len(b)-1]
	}
	if len(b) == 0 {
		return nil
	}
	return bytes.Split(b, []byte("\n"))
}

func main() {
	ins, outs := lines(unpack(inB64)), lines(unpack(outB64))
	table := make(map[string][]byte, len(ins))
	for i := range ins {
		table[string(ins[i])] = outs[i]
	}
	data, _ := io.ReadAll(os.Stdin)
	w := bufio.NewWriter(os.Stdout)
	for _, line := range lines(data) {
		line = bytes.TrimSuffix(line, []byte("\r"))
		if ans, ok := table[string(line)]; ok {
			w.Write(ans)
		} else {
			w.Write(line) // fixed guess: echo the title unchanged
		}
		w.WriteByte('\n')
	}
	w.Flush()
}
EOF

