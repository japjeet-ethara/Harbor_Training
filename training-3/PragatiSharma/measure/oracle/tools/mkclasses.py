"""Generate the Go regex character-class tables from the reference interpreter.

Usage: python -I -B mkclasses.py <go-classes-dump.tsv> <out_tables.go> <out_ref.tsv>

Measures, with Python's own `re` module on every code point (surrogates excepted):
  \\w   (str patterns, as the original's regexes use it)
  \\s
  re.IGNORECASE: which characters a lower-case ASCII letter in a pattern matches.
Writes the differences from the oracle's Go base rules as Go tables, and the full
reference for the exhaustive check (helpers_test.go).
"""
import re
import string
import sys
import unicodedata


def ranges(cps):
    out = []
    for cp in sorted(cps):
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def range_table(name, doc, cps):
    rs = ranges(cps)
    r16 = [r for r in rs if r[1] <= 0xFFFF]
    r32 = [r for r in rs if r[0] > 0xFFFF]
    assert len(r16) + len(r32) == len(rs), "a range crosses U+FFFF"
    latin = sum(1 for r in r16 if r[1] <= 0xFF)
    lines = [f"// {name}: {doc} ({len(cps)} code points)", f"var {name} = &unicode.RangeTable{{"]
    if r16:
        lines.append("\tR16: []unicode.Range16{")
        lines += [f"\t\t{{Lo: 0x{a:04X}, Hi: 0x{b:04X}, Stride: 1}}," for a, b in r16]
        lines.append("\t},")
    if r32:
        lines.append("\tR32: []unicode.Range32{")
        lines += [f"\t\t{{Lo: 0x{a:05X}, Hi: 0x{b:05X}, Stride: 1}}," for a, b in r32]
        lines.append("\t},")
    if latin:
        lines.append(f"\tLatinOffset: {latin},")
    lines.append("}")
    return lines


def main():
    dump_path, out_go, out_ref = sys.argv[1:4]
    go_word, go_space = set(), set()
    go_version = "?"
    for line in open(dump_path, encoding="ascii"):
        if line.startswith("#"):
            go_version = line.split()[-1]
            continue
        cp, w, s = line.rstrip("\n").split("\t")
        if w == "1":
            go_word.add(int(cp, 16))
        if s == "1":
            go_space.add(int(cp, 16))

    cps = [cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF]
    text = "".join(chr(cp) for cp in cps)
    # Measured with the regex engine itself.
    py_word = {ord(m.group()) for m in re.finditer(r"\w", text)}
    py_space = {ord(m.group()) for m in re.finditer(r"\s", text)}
    fold = {}
    for letter in string.ascii_lowercase:
        for m in re.finditer(letter, text, re.IGNORECASE):
            cp = ord(m.group())
            assert cp not in fold, f"U+{cp:04X} matches two letters"
            fold[cp] = letter
    # Cross-checks: str methods agree with the engine, and an IGNORECASE character
    # class matches exactly the union of its letters (as CONSONANTS and [dol] use).
    assert py_word == {cp for cp in cps if chr(cp).isalnum() or chr(cp) == "_"}
    assert py_space == {cp for cp in cps if chr(cp).isspace()}
    consonants = "bcdfghjklmnpqrstvwxz"
    by_class = {ord(m.group()) for m in re.finditer(f"[{consonants}]", text, re.IGNORECASE)}
    assert by_class == {cp for cp, l in fold.items() if l in consonants}
    by_class = {ord(m.group()) for m in re.finditer("[dol]", text, re.IGNORECASE)}
    assert by_class == {cp for cp, l in fold.items() if l in "dol"}

    word_added, word_removed = py_word - go_word, go_word - py_word
    space_added, space_removed = py_space - go_space, go_space - py_space
    # Fold entries the Go rule (ASCII A-Z -> a-z) does not already give.
    fold_extra = {cp: l for cp, l in fold.items() if not (chr(cp) == l or chr(cp) == l.upper())}

    with open(out_ref, "w", encoding="ascii", newline="\n") as ref:
        ref.write(f"# python {sys.version.split()[0]} unicode {unicodedata.unidata_version}\n")
        for cp in cps:
            w, s, f = cp in py_word, cp in py_space, fold.get(cp, "-")
            if w or s or f != "-":
                ref.write(f"{cp:X}\t{int(w)}\t{int(s)}\t{f}\n")

    def name(cp):
        return unicodedata.name(chr(cp), f"U+{cp:04X}")

    py_version = sys.version.split()[0]
    out = [
        f"// Code generated by mkclasses.py from Python {py_version} (Unicode {unicodedata.unidata_version})",
        f"// and Go's unicode package (Unicode {go_version}). DO NOT EDIT.",
        "",
        "package main",
        "",
        'import "unicode"',
        "",
    ]
    out += range_table("pyWordAdded", "\\w in Python but not r == '_' || IsLetter || IsNumber in Go", word_added)
    out.append("")
    out += range_table("pyWordRemoved", "IsLetter or IsNumber in Go but not \\w in Python", word_removed)
    out.append("")
    out += range_table("pySpaceAdded", "\\s in Python but not unicode.IsSpace in Go", space_added)
    out.append("")
    out += range_table("pySpaceRemoved", "unicode.IsSpace in Go but not \\s in Python", space_removed)
    out.append("")
    out.append("// pyIgnoreCaseASCII: non-ASCII characters that a lower-case ASCII letter in a")
    out.append("// pattern matches under re.IGNORECASE.")
    out.append("var pyIgnoreCaseASCII = map[rune]rune{")
    for cp in sorted(fold_extra):
        out.append(f"\t0x{cp:04X}: '{fold_extra[cp]}', // {name(cp)}")
    out.append("}")
    with open(out_go, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")

    def summary(label, s):
        rs = ranges(s)
        print(f"{label}: {len(s)} code points in {len(rs)} ranges")

    print(f"python {py_version} unicode {unicodedata.unidata_version}; go unicode package {go_version}")
    summary("word added (Python \\w, not Go)", word_added)
    summary("word removed (Go, not Python \\w)", word_removed)
    summary("space added (Python \\s, not Go)", space_added)
    summary("space removed (Go, not Python \\s)", space_removed)
    print("space added:", " ".join(f"U+{cp:04X}" for cp in sorted(space_added)))
    print("re.IGNORECASE extra ASCII folds:", ", ".join(f"U+{cp:04X}->{l}" for cp, l in sorted(fold_extra.items())))


if __name__ == "__main__":
    main()
