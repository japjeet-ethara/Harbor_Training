"""Generate the Go casing exception tables from the reference Python interpreter.

Usage: python -I -B mkcasing.py <go-dump.tsv> <out_tables.go> <out_ref.tsv>

For every code point (surrogates excepted) it compares Python's str.upper(),
str.lower() and str.capitalize() of that one character, and the character class
CPython's final-sigma rule uses, with what Go's unicode package gives (from
godump.go). Where they differ, it writes an entry to the Go tables. It also
writes the complete Python reference for the exhaustive check (helpers_test.go).
"""
import sys
import unicodedata

OTHER, CASED, IGNORABLE = 0, 1, 2
CLASS_NAME = {OTHER: "caseOther", CASED: "cased", IGNORABLE: "caseIgnorable"}
# Must match wordBreakMid in pycase.go: Word_Break MidLetter, MidNumLet and
# Single_Quote characters, which are Case_Ignorable without being Mn/Me/Cf/Lm/Sk.
WORD_BREAK_MID = set("'.:··՟״‘’․‧︓﹒﹕＇．：")


def py_class(c):
    # CPython checks Case_Ignorable first, then Cased. Probe both through lower():
    # "cΣ" ends in final sigma only if c is cased and not ignorable;
    # "AcΣ" keeps a medial sigma only if c is neither.
    if (c + "Σ").lower()[-1] == "ς":
        return CASED
    if ("A" + c + "Σ").lower()[-1] == "σ":
        return OTHER
    return IGNORABLE


def go_literal(s):
    return '"' + "".join(f"\\u{ord(c):04X}" if ord(c) <= 0xFFFF else f"\\U{ord(c):08X}" for c in s) + '"'


def hexseq(s):
    return " ".join(f"{ord(c):X}" for c in s)


def main():
    dump_path, out_go, out_ref = sys.argv[1:4]
    go = {}
    go_version = "?"
    for line in open(dump_path, encoding="ascii"):
        if line.startswith("#"):
            go_version = line.split()[-1]
            continue
        f = line.rstrip("\n").split("\t")
        cp, u, l, t = (int(x, 16) for x in f[:4])
        mn, me, cf, lm, sk, lu, ll, lt, ol, ou = (x == "1" for x in f[4:])
        ign = mn or me or cf or lm or sk or chr(cp) in WORD_BREAK_MID
        cased = lu or ll or lt or ol or ou
        go[cp] = (u, l, t, IGNORABLE if ign else CASED if cased else OTHER)

    upper, lower, title, klass = {}, {}, {}, {}
    ref_lines = 0
    with open(out_ref, "w", encoding="ascii", newline="\n") as ref:
        ref.write(f"# python {sys.version.split()[0]} unicode {unicodedata.unidata_version}\n")
        for cp in range(0x110000):
            if 0xD800 <= cp <= 0xDFFF:
                continue
            c = chr(cp)
            gu, gl, gt, gc = go.get(cp, (cp, cp, cp, OTHER))
            if chr(cp) in WORD_BREAK_MID and cp not in go:
                gc = IGNORABLE
            pu, pl, pt, pc = c.upper(), c.lower(), c.capitalize(), py_class(c)
            if pu != chr(gu):
                upper[cp] = pu
            if cp != 0x3A3 and pl != chr(gl):  # capital sigma is handled by context
                lower[cp] = pl
            if pt != chr(gt):
                title[cp] = pt
            if pc != gc:
                klass[cp] = pc
            if pu != c or pl != c or pt != c or pc != OTHER:
                ref.write(f"{cp:X}\t{hexseq(pu)}\t{hexseq(pl)}\t{hexseq(pt)}\t{pc}\n")
                ref_lines += 1

    def name(cp):
        return unicodedata.name(chr(cp), f"U+{cp:04X}")

    py_version = sys.version.split()[0]
    out = [
        f"// Code generated by mkcasing.py from Python {py_version} (Unicode {unicodedata.unidata_version})",
        f"// and Go's unicode package (Unicode {go_version}). DO NOT EDIT.",
        "",
        "package main",
        "",
    ]
    for var, table, doc in (
        ("pyUpperExceptions", upper, "str.upper() of one character, where it differs from unicode.ToUpper."),
        ("pyLowerExceptions", lower, "str.lower() of one character, where it differs from unicode.ToLower."),
        ("pyTitleExceptions", title, "the first character of str.capitalize(), where it differs from unicode.ToTitle."),
    ):
        out.append(f"// {var}: {doc}")
        out.append(f"var {var} = map[rune]string{{")
        for cp in sorted(table):
            out.append(f"\t0x{cp:04X}: {go_literal(table[cp])}, // {name(cp)}")
        out.append("}")
        out.append("")
    out.append("// pySigmaClassExceptions: characters whose Case_Ignorable/Cased class in the")
    out.append("// reference differs from the rule in sigmaClass.")
    out.append("var pySigmaClassExceptions = map[rune]uint8{")
    for cp in sorted(klass):
        out.append(f"\t0x{cp:04X}: {CLASS_NAME[klass[cp]]}, // {name(cp)}")
    out.append("}")
    with open(out_go, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")

    print(f"python {py_version} unicode {unicodedata.unidata_version}; go unicode package {go_version}")
    print(f"upper exceptions {len(upper)} (multi-character {sum(len(v) > 1 for v in upper.values())})")
    print(f"lower exceptions {len(lower)} (multi-character {sum(len(v) > 1 for v in lower.values())})")
    print(f"title exceptions {len(title)} (multi-character {sum(len(v) > 1 for v in title.values())})")
    print(f"sigma class exceptions {len(klass)}")
    print(f"reference rows {ref_lines}")


if __name__ == "__main__":
    main()
