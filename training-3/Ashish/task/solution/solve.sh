func fullUpper(r rune) string {
	if f, ok := caseTable[r]; ok {
		return f.upper
	}
	return string(unicode.ToUpper(r))
}

func fullLowerRune(r rune) string {
	if f, ok := caseTable[r]; ok {
		return f.lower
	}
	return string(unicode.ToLower(r))
}

func fullTitle(r rune) string {
	if f, ok := caseTable[r]; ok {
		return f.title
	}
	return string(unicode.ToTitle(r))
}

func fullUpperString(s string) string {
	var b strings.Builder
	b.Grow(len(s))
	for _, r := range s {
		b.WriteString(fullUpper(r))
	}
	return b.String()
}

// fullLowerString is str.lower(), including the Final_Sigma rule from
// SpecialCasing.txt that CPython applies: a capital sigma lowercases to 'ς'
// when it ends a word and to 'σ' otherwise.
func fullLowerString(s string) string {
	r := []rune(s)
	var b strings.Builder
	b.Grow(len(s))
	for i, ch := range r {
		if ch == '\u03a3' && finalSigma(r, i) {
			b.WriteRune('\u03c2')
			continue
		}
		b.WriteString(fullLowerRune(ch))
	}
	return b.String()
}

func finalSigma(r []rune, i int) bool {
	before := false
	for j := i - 1; j >= 0; j-- {
		if isCaseIgnorable(r[j]) {
			continue
		}
		before = isCased(r[j])
		break
	}
	if !before {
		return false
	}
	for j := i + 1; j < len(r); j++ {
		if isCaseIgnorable(r[j]) {
			continue
		}
		return !isCased(r[j])
	}
	return true
}

func isCased(r rune) bool {
	return unicode.IsUpper(r) || unicode.IsLower(r) || unicode.IsTitle(r) ||
		unicode.In(r, unicode16Cased)
}

func isCaseIgnorable(r rune) bool {
	switch r {
	case '\'', '\u2019', '\u00b7', '\u0387', ':', '.', '\u058a', '\u05f4', '\u2027', '\uff07', '\uff0e', '\ufe13', '\ufe52', '\ufe55':
		return true
	}
	return unicode.In(r, unicode.Mn, unicode.Me, unicode.Cf, unicode.Lm, unicode.Sk)
}

// foldLower maps a rune to the lowest rune in its simple-fold orbit. That is
// the equivalence Python's re.IGNORECASE uses for str patterns, which is why
// 'ſ' (U+017F) matches the 's' in "as" and "vs".
func foldLower(r rune) rune {
	min := r
	for f := unicode.SimpleFold(r); f != r; f = unicode.SimpleFold(f) {
		if f < min {
			min = f
		}
	}
	return min
}

func main() {
	in := bufio.NewScanner(os.Stdin)
	in.Buffer(make([]byte, 0, 64*1024), 4*1024*1024)
	out := bufio.NewWriter(os.Stdout)
	for in.Scan() {
		fmt.Fprintln(out, titlecase(in.Text(), true))
	}
	if err := in.Err(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := out.Flush(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func titlecase(text string, smallFirstLast bool) string {
	lines := splitCollapsed(text)
	processed := make([]string, 0, len(lines))
	for _, line := range lines {
		processed = append(processed, titlecaseLine(line, smallFirstLast))
	}
	return strings.Join(processed, "\n")
}

func titlecaseLine(line string, smallFirstLast bool) string {
	// titlecase/__init__.py:106 -- line.upper() == line, with the FULL mapping.
	allCaps := fullUpperString(line) == line
	words, spaces := splitWS(line)
	tc := make([]string, len(words))
	for i, word := range words {
		tc[i] = processWord(word, allCaps)
	}
	if smallFirstLast && len(tc) > 0 {
		tc[0] = applySmallFirst(tc[0])
		tc[len(tc)-1] = applySmallLast(tc[len(tc)-1])
	}
	return applySubphrase(joinWords(tc, spaces))
}

func processWord(word string, allCaps bool) string {
	if allCaps && isInitials(word) {
		return word
	}
	if apos, ok := applyApos(word); ok {
		return apos
	}
	if prefix, rest, ok := splitMac(word); ok {
		return capitalize(prefix) + titlecase(rest, true)
	}
	if isHonorific(word) {
		return upperFirst(word)
	}
	if hasInlinePeriod(word) || (!allCaps && ucElsewhereMatch(word)) {
		return word
	}
	if isWholeSmall(word) {
		return fullLowerString(word)
	}
	if strings.Contains(word, "/") && !strings.Contains(word, "//") {
		parts := strings.Split(word, "/")
		for i, part := range parts {
			parts[i] = titlecase(part, false)
		}
		return strings.Join(parts, "/")
	}
	if strings.Contains(word, "-") {
		parts := strings.Split(word, "-")
		for i, part := range parts {
			parts[i] = titlecase(part, false)
		}
		return strings.Join(parts, "-")
	}
	if allCaps {
		word = fullLowerString(word)
	}
	if utf8.RuneCountInString(word) > 2 && isAllConsonants(word) {
		return fullUpperString(word)
	}
	return capFirst(word)
}

func splitCollapsed(s string) []string {
	rs := []rune(s)
	var out []string
	start := 0
	for i := 0; i < len(rs); i++ {
		if rs[i] != '\n' && rs[i] != '\r' {
			continue
		}
		out = append(out, string(rs[start:i]))
		for i < len(rs) && (rs[i] == '\n' || rs[i] == '\r') {
			i++
		}
		start = i
		i--
	}
	out = append(out, string(rs[start:]))
	if len(out) == 0 {
		return []string{""}
	}
	return out
}

// isSpace is python's \s for str patterns, i.e. str.isspace(). Go's
// unicode.IsSpace leaves out U+001C..U+001F, which python counts as space.
func isSpace(r rune) bool {
	if r >= 0x1c && r <= 0x1f {
		return true
	}
	return unicode.IsSpace(r)
}

func splitWS(s string) (words, spaces []string) {
	var b strings.Builder
	parts := make([]string, 0)
	flush := func() {
		parts = append(parts, b.String())
		b.Reset()
	}
	for _, r := range s {
		if isSpace(r) {
			flush()
			parts = append(parts, string(r))
			continue
		}
		b.WriteRune(r)
	}
	flush()
	for i, part := range parts {
		if i%2 == 0 {
			words = append(words, part)
		} else {
			spaces = append(spaces, part)
		}
	}
	return words, spaces
}

func joinWords(words, spaces []string) string {
	var b strings.Builder
	n := len(words)
	if len(spaces) > n {
		n = len(spaces)
	}
	for i := 0; i < n; i++ {
		if i < len(words) {
			b.WriteString(words[i])
		}
		if i < len(spaces) {
			b.WriteString(spaces[i])
		}
	}
	return b.String()
}

// isWord is python's \w for str patterns: str.isalnum() plus '_'. isalnum()
// covers Nl and No as well as Nd, which is why this uses unicode.IsNumber
// rather than unicode.IsDigit.
func isWord(r rune) bool {
	return r == '_' || unicode.IsLetter(r) || unicode.IsNumber(r) ||
		unicode.In(r, unicode16Word)
}

func isPunct(r rune) bool {
	return strings.ContainsRune(punctChars, r)
}

func isSubPunct(r rune) bool {
	switch r {
	case ':', '.', ';', '?', '!', '-', '\u2012', '\u2013', '\u2014', '\u2015':
		return true
	default:
		return false
	}
}

func isAZ(b byte) bool {
	return b >= 'A' && b <= 'Z'
}

func isASCIILetter(r rune) bool {
	return (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z')
}

func isInitials(s string) bool {
	if s == "" {
		return false
	}
	var rec func(int) bool
	rec = func(i int) bool {
		if i == len(s) {
			return true
		}
		if i+2 <= len(s) && isAZ(s[i]) && s[i+1] == '.' && rec(i+2) {
			return true
		}
		if i+3 <= len(s) && isAZ(s[i]) && s[i+1] == '.' && isAZ(s[i+2]) && rec(i+3) {
			return true
		}
		return false
	}
	return rec(0)
}

// ucElsewhereMatch is UC_ELSEWHERE (titlecase/__init__.py:47) used as .match()
// at :145, i.e. ANCHORED: r'[PUNCT]*?[a-zA-Z]+[A-Z]+?'. The uppercase letter
// must sit inside the first run of ASCII letters, after an optional run of
// PUNCT characters. The previous version scanned the whole word, so "X-RAY"
// looked like "iPhone" and the hyphen branch at :160 never ran.
func ucElsewhereMatch(word string) bool {
	r := []rune(word)
	for k := 0; k <= len(r); k++ {
		runLen := 0
		for k+runLen < len(r) && isASCIILetter(r[k+runLen]) {
			runLen++
		}
		for m := 1; m < runLen; m++ {
			if r[k+m] >= 'A' && r[k+m] <= 'Z' {
				return true
			}
		}
		// [PUNCT]*? can only advance over PUNCT characters.
		if k == len(r) || !isPunct(r[k]) {
			return false
		}
	}
	return false
}

func applyApos(word string) (string, bool) {
	r := []rune(word)
	if len(r) < 3 {
		return "", false
	}
	switch unicode.ToLower(r[0]) {
	case 'd', 'o', 'l':
	default:
		return "", false
	}
	if r[1] != '\'' && r[1] != '\u2018' {
		return "", false
	}
	// APOS_SECOND is ^[dol]['‘][\w]+(?:['s]{2})?$ with re.I, so everything
	// after r[1] has to split as W + T, where W is a non-empty run of word
	// characters and T is either empty or exactly two characters from the
	// class ['s]. [\w]+ is greedy but backtracks, so "o'reillys'" matches with
	// W = "reilly" and T = "s'", not only "o'reilly's".
	if !aposSplits(r[2:]) {
		return "", false
	}
	first := fullUpper(r[0])
	if !strings.ContainsRune("aeiouAEIOU", r[0]) {
		first = fullLowerRune(r[0])
	}
	return first + string(r[1]) + fullUpper(r[2]) + string(r[3:]), true
}

// aposSplits reports whether s can be split as W + T for APOS_SECOND:
// W a non-empty run of word characters, T empty or exactly two characters
// from the class ['s] (re.I, so 'S' counts too).
func aposSplits(s []rune) bool {
	allWord := func(x []rune) bool {
		for _, c := range x {
			if !isWord(c) {
				return false
			}
		}
		return true
	}
	if len(s) >= 1 && allWord(s) {
		return true
	}
	if len(s) >= 3 && isAposSuf(s[len(s)-2]) && isAposSuf(s[len(s)-1]) && allWord(s[:len(s)-2]) {
		return true
	}
	return false
}

func isAposSuf(r rune) bool {
	return r == '\'' || r == 's' || r == 'S'
}

func splitMac(word string) (prefix, rest string, ok bool) {
	r := []rune(word)
	// MAC_MC is ^([Mm]c|MC)(\w.+), so the remainder needs a word character
	// followed by at least one more character.
	if len(r) < 4 {
		return "", "", false
	}
	mac := (r[0] == 'M' || r[0] == 'm') && r[1] == 'c'
	upperMC := r[0] == 'M' && r[1] == 'C'
	if !mac && !upperMC {
		return "", "", false
	}
	if !isWord(r[2]) {
		return "", "", false
	}
	return string(r[:2]), string(r[2:]), true
}

func isHonorific(word string) bool {
	// MR_MRS_MS_DR is ^((m((rs?)|s))|Dr)$ with re.I.
	switch foldString(word) {
	case "MR", "MRS", "MS", "DR":
		return true
	default:
		return false
	}
}

func foldString(s string) string {
	var b strings.Builder
	for _, r := range s {
		b.WriteRune(foldLower(r))
	}
	return b.String()
}

func hasInlinePeriod(word string) bool {
	r := []rune(word)
	for i := 1; i+1 < len(r); i++ {
		if r[i] == '.' && isWord(r[i-1]) && isWord(r[i+1]) {
			return true
		}
	}
	return false
}

func isWholeSmall(word string) bool {
	r := []rune(word)
	for _, m := range matchers {
		for _, n := range m(r, 0, true) {
			if n == len(r) {
				return true
			}
		}
	}
	return false
}

func isAllConsonants(word string) bool {
	if word == "" {
		return false
	}
	for _, r := range word {
		c := foldLower(r)
		if c < 'A' || c > 'Z' {
			return false
		}
		switch c {
		case 'A', 'E', 'I', 'O', 'U', 'Y':
			return false
		}
	}
	return true
}

// capFirst is CAPFIRST.sub (titlecase/__init__.py:48, :183): ^[PUNCT]*?([\w]).
// The class is LAZY, so at every position [\w] is tried before the position is
// skipped as punctuation. That is what keeps "_dream" lower case while still
// capitalising "(hello)".
func capFirst(word string) string {
	r := []rune(word)
	for i, ch := range r {
		if isWord(ch) {
			return string(r[:i]) + fullUpper(ch) + string(r[i+1:])
		}
		if !isPunct(ch) {
			return word
		}
	}
	return word
}

func upperFirst(s string) string {
	r, size := utf8.DecodeRuneInString(s)
	if size == 0 {
		return s
	}
	return fullUpper(r) + s[size:]
}

// capitalize is python's str.capitalize(): the first character takes the FULL
// title mapping, the rest the FULL lower mapping.
func capitalize(s string) string {
	r := []rune(s)
	if len(r) == 0 {
		return s
	}
	return fullTitle(r[0]) + fullLowerString(string(r[1:]))
}

type matcher func(r []rune, i int, fold bool) []int

var matchers = []matcher{
	lit("a"), lit("an"), lit("and"), lit("as"), lit("at"),
	lit("but"), lit("by"), lit("en"), lit("for"), lit("if"),
	lit("in"), lit("of"), lit("on"), lit("or"), lit("the"), lit("to"),
	optDot("v"), lit("via"), optDot("vs"),
}

func lit(s string) matcher {
	want := []rune(s)
	return func(r []rune, i int, fold bool) []int {
		if i+len(want) > len(r) {
			return nil
		}
		for k, ch := range want {
			got := r[i+k]
			if fold {
				got = foldLower(got)
				ch = foldLower(ch)
			}
			if got != ch {
				return nil
			}
		}
		return []int{len(want)}
	}
}

func optDot(s string) matcher {
	want := []rune(s)
	return func(r []rune, i int, fold bool) []int {
		if i+len(want) > len(r) {
			return nil
		}
		for k, ch := range want {
			got := r[i+k]
			if fold {
				got = foldLower(got)
				ch = foldLower(ch)
			}
			if got != ch {
				return nil
			}
		}
		n := len(want)
		if i+n < len(r) && r[i+n] == '.' {
			return []int{n + 1, n}
		}
		return []int{n}
	}
}

func boundaryAt(r []rune, i int) bool {
	if i < 0 || i > len(r) {
		return false
	}
	var left, right bool
	if i > 0 {
		left = isWord(r[i-1])
	}
	if i < len(r) {
		right = isWord(r[i])
	}
	return left != right
}

func applySmallFirst(s string) string {
	r := []rune(s)
	i := 0
	for i < len(r) && isPunct(r[i]) {
		i++
	}
	for _, m := range matchers {
		for _, n := range m(r, i, true) {
			if boundaryAt(r, i+n) {
				return string(r[:i]) + capitalize(string(r[i:i+n])) + string(r[i+n:])
			}
		}
	}
	return s
}

func applySmallLast(s string) string {
	r := []rune(s)
	for i := 0; i < len(r); i++ {
		if !boundaryAt(r, i) {
			continue
		}
		for _, m := range matchers {
			for _, n := range m(r, i, true) {
				end := i + n
				if end < len(r) && end+1 == len(r) && isPunct(r[end]) {
					end++
				}
				if end == len(r) {
					return string(r[:i]) + capitalize(string(r[i:end]))
				}
			}
		}
	}
	return s
}

func applySubphrase(s string) string {
	r := []rune(s)
	var out []rune
	for i := 0; i < len(r); {
		if isSubPunct(r[i]) && i+1 < len(r) && r[i+1] == ' ' {
			hit := false
			for _, m := range matchers {
				lens := m(r, i+2, false)
				if len(lens) == 0 {
					continue
				}
				n := lens[0]
				out = append(out, r[i], ' ')
				out = append(out, []rune(capitalize(string(r[i+2:i+2+n])))...)
				i += 2 + n
				hit = true
				break
			}
			if hit {
				continue
			}
		}
		out = append(out, r[i])
		i++
	}
	return string(out)
}
