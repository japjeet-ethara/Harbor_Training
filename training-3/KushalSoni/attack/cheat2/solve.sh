// Driver: title-case each stdin line with the original function.
const driver = `
import sys
data = sys.stdin.buffer.read().decode("utf-8", "surrogateescape")
lines = data.split("\n")
if lines and lines[-1] == "":
    lines.pop()
out = [titlecase(l.rstrip("\r")) for l in lines]
sys.stdout.buffer.write("".join(o + "\n" for o in out).encode("utf-8", "surrogateescape"))
`

func main() {
	src, err := base64.StdEncoding.DecodeString(strings.Join(strings.Fields(pySrc), ""))
	if err != nil {
		os.Exit(1)
	}
	code := string(src) + driver
	for _, py := range []string{"python3", "python", "/usr/local/bin/python3", "/usr/bin/python3"} {
		path, err := exec.LookPath(py)
		if err != nil {
			continue
		}
		cmd := exec.Command(path, "-c", code)
		cmd.Stdin, cmd.Stdout, cmd.Stderr = os.Stdin, os.Stdout, os.Stderr
		if cmd.Run() == nil {
			return
		}
	}
	os.Exit(1)
}
