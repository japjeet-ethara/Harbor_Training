import json
import random
from pathlib import Path
from reference import ROOT, load

ref = load()
random.seed(1)
names = dict(small='SMALL_WORDS', first='SMALL_FIRST', last='SMALL_LAST',
             subphrase='SUBPHRASE', mc='MAC_MC', honorific='MR_MRS_MS_DR', inline='INLINE_PERIOD',
             internal='UC_ELSEWHERE', cap='CAPFIRST', apostrophe='APOS_SECOND', initials='UC_INITIALS')
patterns = {k: getattr(ref, v) for k, v in names.items()}
patterns['consonants'] = ref.regex.compile(r'\A[bcdfghjklmnpqrstvwxz]+\Z', ref.regex.I)
samples = ['', 'a', 'an', 'and', 'andante', 'via', 'vs.', 'v.', 'v.s.', 'V.S.', 'A.B',
           'A.B.C', 'A.BC.', 'A.B.A', 'McA', 'McaB', 'MCAB', 'Mc_9', 'McΣΣ',
           "d'art's", "d'art'ss", "d'art''", "l'2", 'o‘İpek', 'mRs', 'MrS', 'dr', 'DR',
           ': andante', '; via', '! vs.', 'x- and', '((the', 'a\n', 'a\r', 'a\n\n',
           'x the!', 'x the!!', 'iPhone', 'aBC', '“aBC', 'a\u0301B', '₿hello', '_abc',
           '\\abc', ']abc', 'Ⅰ.test', 'İ.ı', 'ß.ß', 'İ', 'ı', 'ſ', 'K', 'BſT', 'Σ',
           'a\u0345', 'a\u203f', 'a\u200c', 'a\u2160']
alphabet = "avsiMcrSDR.'‘!:-/\\] AB_xİıſKΣß\u0301\n"
samples += [''.join(random.choices(alphabet, k=random.randrange(25))) for _ in range(2500)]
rows = []
for name, pattern in patterns.items():
    for s in samples:
        for mode in ['match', 'search']:
            m = getattr(pattern, mode)(s)
            rows.append(dict(name=name, mode=mode, input=s, found=m is not None,
                             start=m.start() if m else -1, end=m.end() if m else -1,
                             groups=[m.group(i) or '' for i in range(pattern.groups + 1)] if m else []))
out = ROOT / 'titlecase-go/solution/internal/format/testdata/patterns.json'
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(json.dumps(rows, ensure_ascii=True, separators=(',', ':')) + '\n', encoding='utf-8')
print(f'{len(rows)} direct pattern match/search fixtures generated by CPython before integration checks')
